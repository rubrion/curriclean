export function translate(dict: Dictionary, key: TKey, vars?: Record<string, string | number>): string {
	const s = dict[key] ?? key;
	if (!vars) return s;
	return s.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}
